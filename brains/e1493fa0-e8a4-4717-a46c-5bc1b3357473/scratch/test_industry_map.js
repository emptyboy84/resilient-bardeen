const fs = require('fs');

// Load known mappings from existing project files
const files = ['all_500_factchecked.tsv', 'merged_500_perfect.tsv', 'bizno_filtered_result_nice.csv'];
const map = new Map();

files.forEach(f => {
  if (fs.existsSync(f)) {
    const lines = fs.readFileSync(f, 'utf-8').split('\n');
    lines.forEach(l => {
      if (f === 'merged_500_perfect.tsv' || f === 'all_500_factchecked.tsv') {
        const p = l.split('\t');
        const ind = p[12]?.trim();
        const d = p[15]?.trim();
        const j = p[16]?.trim();
        const s = p[17]?.trim();
        if (ind && d && !map.has(ind)) map.set(ind, { d, j, s });
      }
    });
  }
});

